FString UEstuaryCharacterComponent::SendText(const FString& Text)
{
    check(IsInGameThread());

    if (Text.IsEmpty())
    {
        UE_LOG(LogEstuary, Warning,
            TEXT("[EstuaryCharacterComponent] SendText called with empty text on '%s' — ignored"),
            *CachedCharacterId);
        return FString();
    }

    if (!bIsRegistered)
    {
        UE_LOG(LogEstuary, Warning,
            TEXT("[EstuaryCharacterComponent] SendText: component '%s' is not registered. "
                 "Ensure BeginPlay has completed and a UEstuarySubsystem is available."),
            *CachedCharacterId);
        return FString();
    }

    // Generate a fresh message_id for this turn.
    // Convention: EGuidFormats::Digits = 32-char lowercase hex, no dashes.
    // Matches ts-sdk UUID convention (uuid() stripped of dashes).
    const FString MessageId = FGuid::NewGuid().ToString(EGuidFormats::Digits);
    CurrentMessageId = MessageId;

    // Build the user-text payload.
    FEstuaryUserText Payload;
    Payload.Text        = Text;
    Payload.MessageId   = MessageId;
    Payload.CharacterId = CachedCharacterId;
    Payload.bTextOnly   = false; // Default — audio playback enabled unless caller overrides.

    // Route through the subsystem (which forwards to the bridge).
    UGameInstance* GI = GetOwner() ? GetOwner()->GetGameInstance() : nullptr;
    if (IsValid(GI))
    {
        UEstuarySubsystem* Sub = GI->GetSubsystem<UEstuarySubsystem>();
        if (IsValid(Sub))
        {
            Sub->SendUserText(Payload);
            UE_LOG(LogEstuary, Log,
                TEXT("[EstuaryCharacterComponent] SendText '%s' (message_id=%s len=%d)"),
                *CachedCharacterId, *MessageId, Text.Len());
        }
    }

    return MessageId;
}

void UEstuaryCharacterComponent::SayLine(const FString& Text, bool bTextOnly)
{
    check(IsInGameThread());

    if (Text.IsEmpty())
    {
        UE_LOG(LogEstuary, Warning,
            TEXT("[EstuaryCharacterComponent] SayLine called with empty text on '%s' — ignored"),
            *CachedCharacterId);
        return;
    }

    if (!bIsRegistered)
    {
        UE_LOG(LogEstuary, Warning,
            TEXT("[EstuaryCharacterComponent] SayLine: component '%s' is not registered. "
                 "Ensure BeginPlay has completed and a UEstuarySubsystem is available."),
            *CachedCharacterId);
        return;
    }

    // Unlike SendText, say_line does NOT generate a client-side message_id — the server
    // auto-interrupts the in-flight response and mints its OWN message_id. The response
    // arrives via OnBotResponse / OnBotVoice with that server id. We deliberately do NOT
    // touch CurrentMessageId here (it tracks SendText turns for Interrupt() targeting).

    // Route through the subsystem (which forwards to the bridge).
    UGameInstance* GI = GetOwner() ? GetOwner()->GetGameInstance() : nullptr;
    if (IsValid(GI))
    {
        UEstuarySubsystem* Sub = GI->GetSubsystem<UEstuarySubsystem>();
        if (IsValid(Sub))
        {
            Sub->SendSayLine(Text, bTextOnly);
            UE_LOG(LogEstuary, Log,
                TEXT("[EstuaryCharacterComponent] SayLine '%s' (len=%d text_only=%d)"),
                *CachedCharacterId, Text.Len(), bTextOnly ? 1 : 0);
        }
    }
}

void UEstuaryCharacterComponent::Interrupt()
{
    check(IsInGameThread());

    if (CurrentMessageId.IsEmpty())
    {
        UE_LOG(LogEstuary, Verbose,
            TEXT("[EstuaryCharacterComponent] Interrupt: no active message_id on '%s' — no-op"),
            *CachedCharacterId);
        return;
    }

    FEstuaryInterruptPayload Payload;
    Payload.MessageId   = CurrentMessageId;
    Payload.CharacterId = CachedCharacterId;

    UGameInstance* GI = GetOwner() ? GetOwner()->GetGameInstance() : nullptr;
    if (IsValid(GI))
    {
        UEstuarySubsystem* Sub = GI->GetSubsystem<UEstuarySubsystem>();
        if (IsValid(Sub))
        {
            Sub->SendInterrupt(Payload);
            const TCHAR* ModeName = (Sub->GetVoiceMode() == EEstuaryVoiceMode::LiveKit)
                ? TEXT("LiveKit") : TEXT("WebSocket");
            UE_LOG(LogEstuary, Log,
                TEXT("[EstuaryCharacterComponent] Interrupt '%s' (message_id=%s mode=%s)"),
                *CachedCharacterId, *CurrentMessageId, ModeName);
        }
    }

    // Clear CurrentMessageId so a subsequent Interrupt is a no-op until the next SendText.
    // The component still receives OnInterruptAcked from the subsystem when the ack arrives.
    // In LK mode the room stays open — only the in-flight LLM/TTS turn is aborted server-side.
    CurrentMessageId.Empty();
}

void UEstuaryCharacterComponent::UpdatePreferences(const FEstuaryPreferences& Prefs)
{
    check(IsInGameThread());

    UGameInstance* GI = GetOwner() ? GetOwner()->GetGameInstance() : nullptr;
    if (!IsValid(GI)) { return; }

    UEstuarySubsystem* Sub = GI->GetSubsystem<UEstuarySubsystem>();
    if (!IsValid(Sub)) { return; }

    Sub->SendUpdatePreferences(Prefs);
    UE_LOG(LogEstuary, Log,
        TEXT("[EstuaryCharacterComponent] UpdatePreferences on '%s' (enableVisionAck=%d)"),
        *CachedCharacterId, Prefs.bEnableVisionAcknowledgment ? 1 : 0);
}

bool UEstuaryCharacterComponent::IsRegistered() const
{
    return bIsRegistered;
}

