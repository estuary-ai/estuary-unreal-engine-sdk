void UEstuaryCharacterComponent::BeginPlay()
{
    Super::BeginPlay();
    check(IsInGameThread()); // Always true in BeginPlay; belt-and-suspenders.

    // Cache CharacterId from the owning AEstuaryCharacter.
    // AEstuaryCharacter::BeginPlay runs before UActorComponent::BeginPlay
    // (actor calls Super::BeginPlay which invokes component BeginPlays),
    // so CharacterId is already validated/generated by the time we get here.
    CachedCharacterId = GetCharacterId();

    if (CachedCharacterId.IsEmpty())
    {
        UE_LOG(LogEstuary, Warning,
            TEXT("[EstuaryCharacterComponent] BeginPlay: empty CharacterId on '%s'. "
                 "This component will not receive bot_response routing until CharacterId is set."),
            *GetNameSafe(GetOwner()));
        return;
    }

    // Register with the subsystem so the routing layer knows about this component.
    UGameInstance* GI = GetOwner() ? GetOwner()->GetGameInstance() : nullptr;
    if (!IsValid(GI))
    {
        UE_LOG(LogEstuary, Warning,
            TEXT("[EstuaryCharacterComponent] BeginPlay: no GameInstance — cannot register '%s'"),
            *CachedCharacterId);
        return;
    }

    UEstuarySubsystem* Sub = GI->GetSubsystem<UEstuarySubsystem>();
    if (!IsValid(Sub))
    {
        UE_LOG(LogEstuary, Warning,
            TEXT("[EstuaryCharacterComponent] BeginPlay: UEstuarySubsystem not found — cannot register '%s'"),
            *CachedCharacterId);
        return;
    }

    Sub->RegisterCharacter(this);
    bIsRegistered = true;

    UE_LOG(LogEstuary, Log,
        TEXT("[EstuaryCharacterComponent] Registered '%s' with subsystem."), *CachedCharacterId);
}

void UEstuaryCharacterComponent::EndPlay(const EEndPlayReason::Type EndPlayReason)
{
    check(IsInGameThread());

    if (bIsRegistered)
    {
        UGameInstance* GI = GetOwner() ? GetOwner()->GetGameInstance() : nullptr;
        if (IsValid(GI))
        {
            UEstuarySubsystem* Sub = GI->GetSubsystem<UEstuarySubsystem>();
            if (IsValid(Sub))
            {
                Sub->UnregisterCharacter(this);
            }
        }
        bIsRegistered = false;
        UE_LOG(LogEstuary, Log,
            TEXT("[EstuaryCharacterComponent] Unregistered '%s' from subsystem."), *CachedCharacterId);
    }

    Super::EndPlay(EndPlayReason);
}

