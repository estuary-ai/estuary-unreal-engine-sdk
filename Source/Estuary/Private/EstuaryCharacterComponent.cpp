FString UEstuaryCharacterComponent::GetCharacterId() const
{
    // Prefer the cached value (populated in BeginPlay). Fall through to owner if not yet cached.
    if (!CachedCharacterId.IsEmpty())
    {
        return CachedCharacterId;
    }

    // Pre-BeginPlay path (e.g., subsystem asks before BeginPlay fires — unusual but defensive).
    const AActor* Owner = GetOwner();
    if (!IsValid(Owner)) { return FString(); }

    // AEstuaryCharacter stores CharacterId as a public FString property.
    // We use a Cast here — the component is designed to live on AEstuaryCharacter,
    // but consumers could theoretically attach it to another AActor; return empty in that case.
    if (const AEstuaryCharacter* CharActor = Cast<AEstuaryCharacter>(Owner))
    {
        return CharActor->CharacterId;
    }

    return FString();
}

FName UEstuaryCharacterComponent::GetLiveLinkSubjectName() const
{
    // Resolution order:
    //   1. LiveLinkSubjectOverride (FName UPROPERTY) — disambiguator for shared CharacterIds.
    //   2. CharacterId (FString → FName) — default route for one-character-per-id setups.
    //   3. OwnerActor->GetFName() — last resort if the actor lacks a CharacterId entirely.
    //   4. "EstuaryDefault" — pathological fallback (no owner; should never fire).
    if (!LiveLinkSubjectOverride.IsNone())
    {
        return LiveLinkSubjectOverride;
    }

    // Use the cached CharacterId (post-BeginPlay) when available; otherwise resolve via owner.
    const FString CharId = !CachedCharacterId.IsEmpty()
        ? CachedCharacterId
        : GetCharacterId();
    if (!CharId.IsEmpty())
    {
        return FName(*CharId);
    }

    if (const AActor* Owner = GetOwner())
    {
        return Owner->GetFName();
    }

    return FName(TEXT("EstuaryDefault"));
}

void UEstuaryCharacterComponent::HandleBotAnimationFromSubsystem(
    const FEstuaryBotAnimation& Animation)
{
    // Called on the game thread by UEstuarySubsystem::HandleBotAnimation.
    // Terminator frames are pre-filtered by the subsystem; this always receives
    // renderable frames (FrameIndex >= 0).
    check(IsInGameThread());

    if (!bIsRegistered) { return; }

    OnBotAnimation.Broadcast(Animation);
}

void UEstuaryCharacterComponent::SetEnableAnimation(bool bEnable)
{
    bEnableAnimation = bEnable;

    // Forward to sibling AudioPlayerComponent for sample-rate coercion (ANIM-08 / AUDIO-07).
    AActor* Owner = GetOwner();
    if (IsValid(Owner))
    {
        if (UEstuaryAudioPlayerComponent* Audio =
                Owner->FindComponentByClass<UEstuaryAudioPlayerComponent>())
        {
            Audio->SetEnableAnimation(bEnable);
        }
    }

    if (bEnable)
    {
        UE_LOG(LogEstuary, Log,
            TEXT("[EstuaryCharacterComponent] SetEnableAnimation: enable_animation=true; "
                 "AudioSampleRate will be coerced to 16000 at next Connect()."));
    }
}

