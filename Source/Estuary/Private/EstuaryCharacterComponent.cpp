void UEstuaryCharacterComponent::HandleBotResponseFromSubsystem(const FEstuaryBotResponse& Response)
{
    // Called on game thread by UEstuarySubsystem::HandleBotResponse.
    check(IsInGameThread());

    if (!bIsRegistered)
    {
        // Can happen in the window between EndPlay unregistering and the GC destroying
        // the subsystem entry — drop silently.
        return;
    }

    // Aggregate chunk text for diagnostic logging (not surfaced to Blueprint).
    // Blueprint consumers should concatenate Response.Text themselves if they need the full string.
    UE_LOG(LogEstuary, Verbose,
        TEXT("[EstuaryCharacterComponent] OnBotResponse '%s' chunk_index=%d is_final=%d len=%d"),
        *CachedCharacterId, Response.ChunkIndex, Response.bIsFinal ? 1 : 0, Response.Text.Len());

    // Broadcast to Blueprint — all OnBotResponse event graph nodes fire here.
    // Dynamic multicast delegates are safe to Broadcast on the game thread.
    OnBotResponse.Broadcast(Response);

    // If this is the final chunk, clear CurrentMessageId so Interrupt becomes a no-op.
    if (Response.bIsFinal && Response.MessageId == CurrentMessageId)
    {
        CurrentMessageId.Empty();
    }
}

